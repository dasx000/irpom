-- Skema awal: Monitoring IRPOM (Irigasi Perpompaan) Kabupaten Way Kanan
-- Jalankan manual lewat SQL Editor Supabase, berurutan sesuai nomor file.

create extension if not exists pgcrypto;

-- ============ ENUM ============

create type status_irpom as enum ('Pemberkasan', 'Pembangunan', 'Pemanfaatan', 'Rusak');
create type role_pengguna as enum ('super_admin', 'admin');

-- ============ MASTER WILAYAH ============
-- Sumber tunggal: GeoJSON batas wilayah Way Kanan (public/geo/*.geojson).
-- Isi tabel dibuat oleh scripts/generate-seed.mjs -> 0002_master_wilayah.sql.

create table master_kecamatan (
  id_kecamatan text primary key, -- kode resmi tanpa titik, mis. '180803'
  nama_kecamatan text not null unique
);

create table master_desa (
  id_desa integer generated by default as identity primary key,
  id_kecamatan text not null references master_kecamatan (id_kecamatan) on delete restrict,
  nama_desa text not null,
  unique (id_kecamatan, nama_desa)
);

create index idx_master_desa_kecamatan on master_desa (id_kecamatan);

-- ============ IRPOM (UNIT POMPA) ============
-- Provinsi & kabupaten selalu Lampung / Way Kanan; kecamatan diturunkan dari
-- desa lewat master_desa, sehingga nama wilayah selalu memakai ejaan resmi.
-- Kolom selain wilayah boleh kosong: data bermasalah tetap disimpan dengan
-- kolom terkait dikosongkan (lihat PLAN.md, Aturan Validasi Data).

create table irpom (
  id uuid primary key default gen_random_uuid(),
  provinsi text not null default 'Lampung' check (provinsi = 'Lampung'),
  kabupaten text not null default 'Way Kanan' check (kabupaten = 'Way Kanan'),
  id_desa integer not null references master_desa (id_desa) on delete restrict,
  kelompok_tani text,
  ketua_poktan text,
  volume integer not null default 1,
  luas_ha numeric(10, 2),
  tahun_anggaran smallint,
  sumber_dana text,
  status status_irpom default 'Pemberkasan',
  latitude double precision,
  longitude double precision,
  keterangan text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index idx_irpom_desa on irpom (id_desa);
create index idx_irpom_status on irpom (status);
create index idx_irpom_tahun on irpom (tahun_anggaran);

create function set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger trg_irpom_updated_at
  before update on irpom
  for each row execute function set_updated_at();

-- ============ PROFILES (ROLE & AKSES) ============

create table profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  nama text,
  role role_pengguna not null default 'admin',
  aktif boolean not null default true,
  created_at timestamptz not null default now()
);

-- Baris profiles dibuat otomatis saat akun dibuat (oleh Super Admin lewat
-- aplikasi, atau lewat dashboard Supabase). Pendaftaran publik dimatikan.
create function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, nama)
  values (new.id, new.email, new.raw_user_meta_data ->> 'nama');
  return new;
end;
$$;

create trigger trg_on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

-- ============ HELPER UNTUK RLS ============
-- security definer supaya bisa membaca profiles tanpa terjebak RLS-nya sendiri.
-- Akun nonaktif dianggap tidak punya role.

create function app_current_role() returns role_pengguna
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid() and aktif;
$$;

create function is_pengelola() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(app_current_role() in ('super_admin', 'admin'), false);
$$;

create function is_super_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(app_current_role() = 'super_admin', false);
$$;

-- ============ AUDIT LOG ============
-- Diisi otomatis oleh trigger; irpom_id sengaja tanpa foreign key supaya
-- riwayat unit yang sudah dihapus tetap tersimpan.

create table irpom_audit_log (
  id bigint generated always as identity primary key,
  irpom_id uuid not null,
  aksi text not null check (aksi in ('insert', 'update', 'delete')),
  data_lama jsonb,
  data_baru jsonb,
  user_id uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create index idx_audit_irpom on irpom_audit_log (irpom_id);
create index idx_audit_user on irpom_audit_log (user_id);
create index idx_audit_created on irpom_audit_log (created_at desc);

create function catat_audit_irpom() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into irpom_audit_log (irpom_id, aksi, data_baru, user_id)
    values (new.id, 'insert', to_jsonb(new), auth.uid());
    return new;
  elsif tg_op = 'UPDATE' then
    insert into irpom_audit_log (irpom_id, aksi, data_lama, data_baru, user_id)
    values (new.id, 'update', to_jsonb(old), to_jsonb(new), auth.uid());
    return new;
  else
    insert into irpom_audit_log (irpom_id, aksi, data_lama, user_id)
    values (old.id, 'delete', to_jsonb(old), auth.uid());
    return old;
  end if;
end;
$$;

create trigger trg_irpom_audit
  after insert or update or delete on irpom
  for each row execute function catat_audit_irpom();

-- ============ ROW LEVEL SECURITY ============

alter table master_kecamatan enable row level security;
alter table master_desa enable row level security;
alter table irpom enable row level security;
alter table profiles enable row level security;
alter table irpom_audit_log enable row level security;

-- Master wilayah: dibaca siapa saja (dropdown form & filter publik), tidak bisa diubah lewat API.
create policy "master_kecamatan dibaca semua" on master_kecamatan
  for select to anon, authenticated using (true);
create policy "master_desa dibaca semua" on master_desa
  for select to anon, authenticated using (true);

-- IRPOM: tabel dasar hanya untuk pengelola. Publik membaca lewat RPC di
-- 0004_rpc_publik.sql yang tidak memuat kolom keterangan.
create policy "irpom dibaca pengelola" on irpom
  for select to authenticated using (is_pengelola());
create policy "irpom ditambah pengelola" on irpom
  for insert to authenticated with check (is_pengelola());
create policy "irpom diubah pengelola" on irpom
  for update to authenticated using (is_pengelola()) with check (is_pengelola());
create policy "irpom dihapus pengelola" on irpom
  for delete to authenticated using (is_pengelola());

-- Profiles: tiap akun membaca profilnya sendiri; Super Admin membaca semua.
-- Perubahan role/aktif dan pembuatan akun dilakukan lewat server (service role).
create policy "profil sendiri dibaca" on profiles
  for select to authenticated using (id = auth.uid() or is_super_admin());
create policy "nama profil sendiri diubah" on profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Kolom yang boleh diubah sendiri hanya nama (role, aktif, email lewat server).
revoke update on profiles from authenticated;
grant update (nama) on profiles to authenticated;

-- Audit log: hanya dibaca Super Admin; penulisan hanya lewat trigger.
create policy "audit dibaca super admin" on irpom_audit_log
  for select to authenticated using (is_super_admin());
